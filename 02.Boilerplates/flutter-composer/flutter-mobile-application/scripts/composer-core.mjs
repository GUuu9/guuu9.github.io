import { readdir, readFile, lstat, mkdir, writeFile, rm } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { createHash } from 'node:crypto';

export const targets = ['android', 'ios', 'android-ios'];
export const hash = value => createHash('sha256').update(value).digest('hex');
const excluded = new Set(['.git', '.fvm', '.dart_tool', '.pub-cache', '.pub', '.idea', '.gradle', 'build', 'node_modules', 'Pods', '.symlinks', '.local', '.direnv', '.bundle', '.DS_Store', 'local.properties', 'key.properties', 'Generated.xcconfig', 'flutter_export_environment.sh']);
export async function collect(root, prefix = '', files = new Map()) {
  for (const entry of await readdir(join(root, prefix), { withFileTypes: true })) {
    if (excluded.has(entry.name) || (entry.name.startsWith('.env') && entry.name !== '.env.example') || /\.(jks|keystore|p12|mobileprovision)$/.test(entry.name)) continue;
    const name = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isSymbolicLink()) throw new Error(`템플릿 심볼릭 링크: ${name}`);
    if (entry.isDirectory()) await collect(root, name, files);
    else files.set(name, await readFile(join(root, name)));
  }
  return files;
}
export function relativePath(name) {
  if (typeof name !== 'string' || !/^[a-zA-Z0-9_.\-/]+$/.test(name) || name.startsWith('/') || name.split('/').some(part => !part || part === '.' || part === '..')) throw new Error(`허용하지 않는 파일 경로: ${name}`);
  return name;
}
export async function safePath(root, name) {
  relativePath(name);
  let path = root;
  for (const part of name.split('/')) {
    path = join(path, part);
    try { if ((await lstat(path)).isSymbolicLink()) throw new Error(`심볼릭 링크 경로: ${name}`); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  return path;
}
export async function optionalRead(path) {
  try { return await readFile(path); }
  catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}
export async function featureCatalog(directory) {
  const files = await collect(directory);
  const definitions = new Map();
  for (const [name, value] of files) {
    if (!name.endsWith('/compose.json')) continue;
    const definition = JSON.parse(value);
    const allowed = ['id', 'version', 'description', 'targets', 'entry', 'factory', 'assets'];
    if (Object.keys(definition).some(key => !allowed.includes(key))) throw new Error(`지원하지 않는 feature 선언 필드: ${name}`);
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(definition.id) || definitions.has(definition.id) || !/^\d+\.\d+\.\d+$/.test(definition.version) || typeof definition.description !== 'string' || !Array.isArray(definition.targets) || !definition.targets.length || definition.targets.some(target => !targets.includes(target)) || !/^[a-zA-Z][a-zA-Z0-9]*$/.test(definition.factory) || !Array.isArray(definition.assets)) throw new Error(`feature 선언 형식: ${name}`);
    relativePath(definition.entry);
    if (!definition.entry.endsWith('.dart')) throw new Error(`Dart 진입점 필요: ${name}`);
    const prefix = name.slice(0, -'compose.json'.length) + 'files/';
    const payload = new Map([...files].filter(([file]) => file.startsWith(prefix)).map(([file, data]) => [relativePath(file.slice(prefix.length)), data]));
    if (!payload.has(`lib/${definition.entry}`)) throw new Error(`feature 진입점 없음: ${name}`);
    for (const asset of definition.assets) if (!payload.has(relativePath(asset))) throw new Error(`asset 파일 없음: ${asset}`);
    for (const path of payload.keys()) if (!/^(lib\/|test\/|docs\/)/.test(path) || path.startsWith('lib/core/')) throw new Error(`feature는 전용 lib/test/docs 파일만 추가합니다: ${path}`);
    definitions.set(definition.id, { ...definition, payload });
  }
  return { definitions, files };
}
export const assetsStart = '  # composer:assets:start';
export const assetsEnd = '  # composer:assets:end';
export function assetBlock(pubspec) {
  if (pubspec.split(assetsStart).length !== 2 || pubspec.split(assetsEnd).length !== 2) throw new Error('pubspec assets 관리 구간이 변경되었습니다.');
  const start = pubspec.indexOf(assetsStart), end = pubspec.indexOf(assetsEnd) + assetsEnd.length;
  if (end <= start) throw new Error('pubspec assets 구간 순서 오류');
  return pubspec.slice(start, end);
}
export function registry(definitions) {
  return '// GENERATED by scripts/feature.mjs. Do not edit.\n' + "import 'app_feature.dart';\n" + definitions.map((definition, index) => `import '../${definition.entry}' as feature${index};\n`).join('') + '\nList<AppFeature> createFeatures() => [' + definitions.map((definition, index) => `\n  feature${index}.${definition.factory}(),`).join('') + (definitions.length ? '\n' : '') + '];\n';
}
export async function planFeatures(root, state, names) {
  const { definitions } = await featureCatalog(await safePath(root, '.composer/features'));
  const selectedIds = [...new Set([...state.features.map(feature => feature.id), ...names])];
  const selected = selectedIds.map(id => {
    const definition = definitions.get(id);
    if (!definition || !definition.targets.includes(state.target)) throw new Error(`지원하지 않는 기능/형태: ${id} / ${state.target}`);
    const active = state.features.find(feature => feature.id === id);
    if (active && active.version !== definition.version) throw new Error(`활성 기능의 catalog 버전이 변경됐습니다: ${id}`);
    return definition;
  });
  const additions = selected.filter(feature => !state.features.some(active => active.id === feature.id));
  const changes = new Map();
  for (const definition of additions) {
    for (const [name, original] of definition.payload) {
      if (changes.has(name) || await optionalRead(await safePath(root, name)) !== null) throw new Error(`기능 파일 충돌: ${name}`);
      changes.set(name, name.endsWith('.dart') ? Buffer.from(original.toString().replaceAll('package:mobile_app_sample/', `package:${state.packageName}/`)) : original);
    }
  }
  const generated = 'lib/core/features.g.dart';
  const current = await optionalRead(await safePath(root, generated));
  if (!current || hash(current) !== state.hashes[generated]) throw new Error(`생성 연결 파일에 사용자 변경: ${generated}`);
  changes.set(generated, Buffer.from(registry(selected)));
  const pubspec = (await readFile(await safePath(root, 'pubspec.yaml'))).toString();
  if (!pubspec.startsWith(`name: ${state.packageName}\n`)) throw new Error('Dart package 이름과 Composer 상태가 일치하지 않습니다.');
  const block = assetBlock(pubspec);
  if (block !== state.assetBlock) throw new Error('pubspec assets 관리 구간에 사용자 변경');
  const assets = [...new Set(selected.flatMap(feature => feature.assets))];
  const nextBlock = assetsStart + (assets.length ? '\n  assets:\n' + assets.map(asset => `    - ${asset}`).join('\n') : '') + '\n' + assetsEnd;
  // 사용자 asset은 관리 구간의 assets 목록에 추가하지 않고 별도 소유 구조를 설계합니다.
  if (/^  assets:/m.test(pubspec.replace(block, ''))) throw new Error('pubspec 외부 assets 목록과 자동 등록이 충돌합니다.');
  changes.set('pubspec.yaml', Buffer.from(pubspec.replace(block, nextBlock)));
  const next = { ...state, features: selected.map(({ id, version, description }) => ({ id, version, description })), hashes: { ...state.hashes, [generated]: hash(changes.get(generated)) }, assetBlock: nextBlock };
  return { changes, next };
}
export async function applyChanges(root, changes, next, verify) {
  const originals = new Map();
  for (const name of [...changes.keys(), 'pubspec.lock', '.composer/state.json']) originals.set(name, await optionalRead(await safePath(root, name)));
  try {
    for (const [name, value] of changes) {
      const path = await safePath(root, name);
      await mkdir(dirname(path), { recursive: true }); await writeFile(path, value);
    }
    await verify();
    await writeFile(await safePath(root, '.composer/state.json'), JSON.stringify(next, null, 2) + '\n');
  } catch (error) {
    for (const [name, original] of originals) {
      const path = await safePath(root, name);
      if (original === null) await rm(path, { force: true });
      else await writeFile(path, original);
    }
    throw error;
  }
}
